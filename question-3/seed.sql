-- Simplified fact table for ad campaign conversions
CREATE TABLE fact_ad_conversions (
    conversion_id TEXT PRIMARY KEY,
    campaign_id TEXT NOT NULL,
    ad_id TEXT NOT NULL,
    user_id TEXT NOT NULL,
    conversion_date DATE NOT NULL,
    conversion_type TEXT NOT NULL CHECK(conversion_type IN ('purchase', 'signup', 'app_install', 'add_to_cart', 'lead_form')),
    conversion_value REAL DEFAULT 0.0,
    device_type TEXT CHECK(device_type IN ('mobile', 'desktop', 'tablet')),
    placement TEXT CHECK(placement IN ('feed', 'stories', 'reels', 'explore')),
    age_group TEXT CHECK(age_group IN ('18-24', '25-34', '35-44', '45-54', '55+')),
    gender TEXT CHECK(gender IN ('male', 'female', 'other')),
    country TEXT NOT NULL
);

